#!/usr/bin/env node
/**
 * CrewCue knowledge base generator.
 *
 * Reads the code and writes the fact pages under docs/kb/generated/: API routes and their
 * auth guards, the Postgres schema, the module graph, config, and risk signals. Output is
 * deterministic (no timestamps, no git history) so CI can fail when the pages drift.
 *
 *   node scripts/kb/generate-kb.mjs          # rewrite docs/kb/generated
 *   node scripts/kb/generate-kb.mjs --check  # exit 1 if any page is stale
 */
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import {
  parseRoutes,
  parseMigrations,
  parseImports,
  parseEnvReads,
  parseSwiftTypes,
  countMarkers,
  findTimers
} from "./kbParse.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const outDir = path.join(repoRoot, "docs/kb/generated");
const checkMode = process.argv.includes("--check");

const LARGE_FILE_LINES = 800;
const API_SRC = "services/api/src";

function listFiles() {
  const out = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard"], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024
  });
  return out
    .split("\n")
    .filter(Boolean)
    .filter((file) => fs.existsSync(path.join(repoRoot, file)))
    .sort();
}

const files = listFiles();
const cache = new Map();
function read(file) {
  if (!cache.has(file)) cache.set(file, fs.readFileSync(path.join(repoRoot, file), "utf8"));
  return cache.get(file);
}
const lineCount = (file) => read(file).split("\n").length;
const isTest = (file) => /\.test\.(ts|mjs|js)$|Tests?\.(swift|kt)$|\/(Tests|test|androidTest|CrewCueUITests)\//.test(file);
const link = (file, line) => `[${file}${line ? `:${line}` : ""}](../../../${file}${line ? `#L${line}` : ""})`;
const code = (text) => `\`${text}\``;

const HEADER = (title, blurb) =>
  `<!-- GENERATED by scripts/kb/generate-kb.mjs — do not edit. Run \`npm run kb:generate\`. -->\n# ${title}\n\n${blurb}\n`;

// ---------------------------------------------------------------- API routes
const apiSource = files.filter((f) => f.startsWith(API_SRC) && f.endsWith(".ts") && !isTest(f));
const routeFiles = apiSource.filter((f) => f.startsWith(`${API_SRC}/routes/`));
const routes = routeFiles.flatMap((file) => parseRoutes(read(file)).map((route) => ({ ...route, file })));

function routesPage() {
  const byGuard = {};
  for (const r of routes) byGuard[r.guard] = (byGuard[r.guard] ?? 0) + 1;
  let md = HEADER(
    "API routes",
    "Every Fastify route in `services/api/src/routes`, with the auth guard the generator found in the handler. " +
      "Guards are detected by pattern, so `none detected` means *look*, not *open*: health checks and join previews are public on purpose."
  );
  md += `\n**${routes.length} routes** in ${routeFiles.length} files. Guards: ${Object.entries(byGuard)
    .sort()
    .map(([g, n]) => `${g} ${n}`)
    .join(", ")}.\n`;
  md += `\nGuard key: ${code("identity")} checks ${code("request.identity")} (Auth0 JWT, set by ${code("plugins/auth.ts")}); ` +
    `${code("room-member")} / ${code("course-editor")} call ${code("requireRoomMember")} / ${code("requireCourseEditor")}; ` +
    `${code("+ membership")} / ${code("+ owner")} means the handler also checks the room's memberships or athlete inline; ` +
    `${code("shared-secret")} compares a header against an env secret; ${code("automation")} uses the automation guard.\n`;
  for (const file of routeFiles) {
    const rows = routes.filter((r) => r.file === file);
    if (rows.length === 0) continue;
    md += `\n## ${path.basename(file, ".ts")}\n\n| Method | Path | Guard | Source |\n| --- | --- | --- | --- |\n`;
    for (const r of rows) md += `| ${r.method} | ${code(r.path)} | ${r.guard} | ${link(file, r.line)} |\n`;
  }
  return md;
}

// ---------------------------------------------------------------- Data model
const migrationFiles = files.filter((f) => /^services\/api\/db\/migrations\/.*\.sql$/.test(f));
const schema = parseMigrations(migrationFiles.map((file) => ({ file, text: read(file) })));

function dataModelPage() {
  let md = HEADER(
    "Data model",
    "Postgres schema rebuilt from `services/api/db/migrations` in order, and the API files that name each table. " +
      "In `PERSISTENCE_MODE=memory` none of these tables exist; the same stores keep state in process."
  );
  md += `\n**${schema.tables.length} tables** from ${migrationFiles.length} migrations.`;
  if (schema.dropped.length) md += ` Dropped: ${schema.dropped.map(code).join(", ")}.`;
  md += "\n";
  for (const table of schema.tables) {
    const users = apiSource.filter((f) => new RegExp(`\\b${table.name}\\b`).test(read(f)));
    md += `\n## ${code(table.name)}\n\nCreated in ${link(table.createdIn)}.`;
    if (table.alteredIn.length) md += ` Altered in ${table.alteredIn.map((f) => link(f)).join(", ")}.`;
    md += "\n\n| Column | Type |\n| --- | --- |\n";
    for (const col of table.columns) md += `| ${code(col.name)} | ${col.type} |\n`;
    if (table.primaryKey) md += `\nPrimary key: ${code(table.primaryKey)}.\n`;
    if (table.indexes.length) md += `\nIndexes: ${table.indexes.map(code).join(", ")}.\n`;
    md += `\nRead/written by: ${users.length ? users.map((f) => link(f)).join(", ") : "_no API file names this table_"}.\n`;
  }
  return md;
}

// ---------------------------------------------------------------- Modules
function workspaces() {
  const root = JSON.parse(read("package.json"));
  const pkgFiles = files.filter((f) => /^(apps|services|packages)\/[^/]+\/package\.json$/.test(f));
  const pkgs = pkgFiles.map((file) => ({ file, json: JSON.parse(read(file)) }));
  const names = new Set(pkgs.map((p) => p.json.name));
  return {
    globs: root.workspaces,
    packages: pkgs.map(({ file, json }) => ({
      name: json.name,
      dir: path.dirname(file),
      description: json.description ?? "",
      internalDeps: Object.keys({ ...json.dependencies, ...json.devDependencies }).filter((d) => names.has(d)).sort(),
      externalDeps: Object.keys(json.dependencies ?? {}).filter((d) => !names.has(d)).sort()
    }))
  };
}

function apiImportGraph() {
  const set = new Set(apiSource);
  const edges = new Map();
  for (const file of apiSource) {
    const deps = parseImports(read(file))
      .filter((spec) => spec.startsWith("."))
      .map((spec) => path.posix.normalize(path.posix.join(path.posix.dirname(file), spec)).replace(/\.js$/, ".ts"))
      .map((target) => (set.has(target) ? target : set.has(`${target}/index.ts`) ? `${target}/index.ts` : null))
      .filter(Boolean);
    edges.set(file, [...new Set(deps)].sort());
  }
  const fanIn = new Map(apiSource.map((f) => [f, 0]));
  for (const deps of edges.values()) for (const d of deps) fanIn.set(d, fanIn.get(d) + 1);
  return { edges, fanIn };
}

function clientInventory() {
  const groups = [
    { name: "client-core (Swift, shared)", prefix: "packages/client-core/Sources/", ext: ".swift" },
    { name: "iOS app (SwiftUI)", prefix: "apps/ios/CrewCue/", ext: ".swift" },
    { name: "Android app (Compose)", prefix: "apps/android/app/src/main/", ext: ".kt" }
  ];
  return groups.map((g) => {
    const list = files.filter((f) => f.startsWith(g.prefix) && f.endsWith(g.ext) && !isTest(f));
    const dirs = {};
    for (const f of list) {
      const rel = path.posix.dirname(f.slice(g.prefix.length)) || ".";
      dirs[rel] ??= { files: 0, lines: 0 };
      dirs[rel].files += 1;
      dirs[rel].lines += lineCount(f);
    }
    return { ...g, list, dirs };
  });
}

function modulesPage() {
  const ws = workspaces();
  const { edges, fanIn } = apiImportGraph();
  const clients = clientInventory();
  let md = HEADER(
    "Modules",
    "Workspaces, the API's internal import graph, and the native client trees. Narrative: [architecture.md](../architecture.md)."
  );
  md += "\n## Workspaces\n\n| Package | Path | Internal deps | Runtime deps |\n| --- | --- | --- | --- |\n";
  for (const p of ws.packages) {
    md += `| ${code(p.name)} | ${code(p.dir)} | ${p.internalDeps.map(code).join(", ") || "—"} | ${p.externalDeps.map(code).join(", ") || "—"} |\n`;
  }
  md += "\nNon-npm trees: `packages/client-core` (SwiftPM), `apps/ios` (Xcode), `apps/android` (Gradle).\n";

  md += "\n## API: route files → libraries\n\nWhich `lib/` modules each route file imports directly.\n\n| Route file | Imports |\n| --- | --- |\n";
  for (const file of routeFiles) {
    const deps = edges.get(file).filter((d) => d.includes("/lib/")).map((d) => code(d.replace(`${API_SRC}/lib/`, "")));
    md += `| ${link(file)} | ${deps.join(", ") || "—"} |\n`;
  }

  md += "\n## API: most depended-on modules\n\nHigh fan-in modules are where a change spreads furthest.\n\n| Module | Imported by | Lines |\n| --- | --- | --- |\n";
  [...fanIn.entries()]
    .filter(([, n]) => n >= 3)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .forEach(([file, n]) => (md += `| ${link(file)} | ${n} | ${lineCount(file)} |\n`));

  md += "\n## client-core types\n\nTop-level Swift types per file in `packages/client-core/Sources` (shared by iOS and Android).\n\n| File | Types |\n| --- | --- |\n";
  for (const file of clients[0].list) {
    const types = parseSwiftTypes(read(file));
    md += `| ${link(file)} | ${types.slice(0, 12).map(code).join(", ")}${types.length > 12 ? ` +${types.length - 12}` : ""} |\n`;
  }

  md += "\n## Native client trees\n";
  for (const g of clients) {
    md += `\n### ${g.name}\n\n${g.list.length} files under ${code(g.prefix)}.\n\n| Directory | Files | Lines |\n| --- | --- | --- |\n`;
    for (const [dir, s] of Object.entries(g.dirs).sort()) md += `| ${code(dir)} | ${s.files} | ${s.lines} |\n`;
  }
  return md;
}

// ---------------------------------------------------------------- Config
const configScanFiles = files.filter(
  (f) => /^(services|packages)\/[^/]+\/(src|scripts)\//.test(f) && /\.(ts|mjs|js)$/.test(f) && !isTest(f)
);
const envReads = new Map();
for (const file of configScanFiles) {
  for (const name of parseEnvReads(read(file))) {
    if (!envReads.has(name)) envReads.set(name, new Set());
    envReads.get(name).add(file);
  }
}
const SECRET_RE = /SECRET|TOKEN|PASSWORD|PRIVATE|_KEY$|DATABASE_URL/;

function configPage() {
  let md = HEADER(
    "Configuration",
    "Environment variables read by the API and shared packages, and where. Values live in Railway; templates in `*.env.example`. " +
      "Secret-shaped names are marked so a reviewer notices a new one."
  );
  md += `\n**${envReads.size} variables.**\n\n| Variable | Secret-shaped | Read in |\n| --- | --- | --- |\n`;
  for (const [name, set] of [...envReads.entries()].sort()) {
    md += `| ${code(name)} | ${SECRET_RE.test(name) ? "yes" : ""} | ${[...set].sort().map((f) => link(f)).join(", ")} |\n`;
  }
  const examples = files.filter((f) => /\.env(\.[\w-]+)?\.example$/.test(f));
  if (examples.length) {
    const documented = new Set(examples.flatMap((f) => [...read(f).matchAll(/^\s*#?\s*([A-Z][A-Z0-9_]+)=/gm)].map((m) => m[1])));
    const missing = [...envReads.keys()].filter((n) => !documented.has(n)).sort();
    md += `\n## Not in any \`.env*.example\`\n\nTemplates: ${examples.map((f) => link(f)).join(", ")}.\n\n`;
    md += missing.length ? missing.map((n) => `- ${code(n)}`).join("\n") + "\n" : "_All documented._\n";
  }
  return md;
}

// ---------------------------------------------------------------- Risk signals
function riskSignalsPage() {
  const sourceFiles = files.filter(
    (f) => /^(services|packages|apps)\//.test(f) && /\.(ts|mjs|swift|kt)$/.test(f) && !isTest(f) && !f.includes("/Generated/")
  );
  const unguarded = routes.filter((r) => r.guard === "none detected");
  const roomScopedIdentityOnly = routes.filter((r) => /:roomId\b/.test(r.path) && r.guard === "identity");
  const large = sourceFiles
    .map((f) => ({ file: f, lines: lineCount(f) }))
    .filter((x) => x.lines >= LARGE_FILE_LINES)
    .sort((a, b) => b.lines - a.lines || a.file.localeCompare(b.file));
  const markers = sourceFiles
    .map((f) => ({ file: f, ...countMarkers(read(f)) }))
    .filter((x) => x.total > 0)
    .sort((a, b) => b.total - a.total || a.file.localeCompare(b.file));
  const timers = apiSource.flatMap((f) => findTimers(read(f)).map((t) => ({ file: f, ...t })));
  const untestedLib = apiSource
    .filter((f) => f.startsWith(`${API_SRC}/lib/`) && !f.endsWith("/types.ts") && !f.endsWith("/index.ts"))
    .filter((f) => {
      const base = path.basename(f, ".ts");
      return !files.some((t) => isTest(t) && t.startsWith("services/api/") && path.basename(t).startsWith(`${base}.`));
    });
  let behavior = { features: [] };
  try {
    behavior = JSON.parse(read("clients/behavior/deeplinks.json"));
  } catch {}
  const parityGaps = (behavior.features ?? []).filter((f) => f.ios !== "pass" || f.android !== "pass");

  let md = HEADER(
    "Risk signals",
    "Mechanical signals worth a human look. Each is a pointer, not a verdict; triage lives in [risks.md](../risks.md)."
  );
  md += `\n| Signal | Count |\n| --- | --- |\n| Routes with no auth guard detected | ${unguarded.length} |\n| Room-scoped routes with no membership check detected | ${roomScopedIdentityOnly.length} |\n| Source files ≥ ${LARGE_FILE_LINES} lines | ${large.length} |\n| In-process timers in the API | ${timers.length} |\n| API lib modules with no same-named test | ${untestedLib.length} |\n| Native features not passing on both platforms | ${parityGaps.length} |\n| Files with TODO/FIXME/HACK | ${markers.length} |\n`;

  md += "\n## Routes with no auth guard detected\n\nConfirm each is public on purpose, or guarded somewhere the generator cannot see.\n\n";
  md += unguarded.length
    ? "| Method | Path | Source |\n| --- | --- | --- |\n" + unguarded.map((r) => `| ${r.method} | ${code(r.path)} | ${link(r.file, r.line)} |`).join("\n") + "\n"
    : "_None._\n";

  md += "\n## Room-scoped routes with no membership check detected\n\nThe caller is signed in, but the generator saw no room membership or owner check. Any signed-in user may reach another crew's room.\n\n";
  md += roomScopedIdentityOnly.length
    ? "| Method | Path | Source |\n| --- | --- | --- |\n" + roomScopedIdentityOnly.map((r) => `| ${r.method} | ${code(r.path)} | ${link(r.file, r.line)} |`).join("\n") + "\n"
    : "_None._\n";

  md += `\n## Large files\n\nFiles over ${LARGE_FILE_LINES} lines concentrate merge conflicts and review misses.\n\n| File | Lines |\n| --- | --- |\n`;
  md += large.map((x) => `| ${link(x.file)} | ${x.lines} |`).join("\n") + "\n";

  md += "\n## In-process timers (API)\n\nTimers run per instance. With more than one API replica each one fires.\n\n";
  md += timers.length
    ? "| Kind | Source |\n| --- | --- |\n" + timers.map((t) => `| ${code(t.kind)} | ${link(t.file, t.line)} |`).join("\n") + "\n"
    : "_None._\n";

  md += "\n## API lib modules with no same-named test\n\nMay still be covered through route tests; check before relying on it.\n\n";
  md += untestedLib.map((f) => `- ${link(f)}`).join("\n") + "\n";

  md += "\n## Native parity gaps\n\nFrom `clients/behavior/deeplinks.json`. `pass` requires a device proof file.\n\n";
  md += parityGaps.length
    ? "| Feature | Scope | iOS | Android |\n| --- | --- | --- | --- |\n" +
      parityGaps.map((f) => `| ${code(f.id)} | ${f.scope ?? ""} | ${f.ios} | ${f.android} |`).join("\n") + "\n"
    : "_All features pass on both platforms._\n";
  if (behavior.deferred?.length) md += `\nDeferred: ${behavior.deferred.map(code).join(", ")}.\n`;

  md += "\n## TODO / FIXME / HACK\n\n";
  md += markers.length
    ? "| File | TODO | FIXME | HACK |\n| --- | --- | --- | --- |\n" + markers.map((x) => `| ${link(x.file)} | ${x.TODO} | ${x.FIXME} | ${x.HACK} |`).join("\n") + "\n"
    : "_None._\n";
  return { md, summary: { unguarded: unguarded.length, roomScopedIdentityOnly: roomScopedIdentityOnly.length, large: large.length, timers: timers.length, untestedLib: untestedLib.length, parityGaps: parityGaps.length } };
}

// ---------------------------------------------------------------- Index + write
const risk = riskSignalsPage();
const pages = {
  "api-routes.md": routesPage(),
  "data-model.md": dataModelPage(),
  "modules.md": modulesPage(),
  "config.md": configPage(),
  "risk-signals.md": risk.md
};
pages["kb.json"] =
  JSON.stringify(
    {
      routes: routes.map(({ method, path: p, guard, file, line }) => ({ method, path: p, guard, file, line })),
      tables: schema.tables.map((t) => ({ name: t.name, columns: t.columns.map((c) => c.name), createdIn: t.createdIn })),
      env: Object.fromEntries([...envReads.entries()].sort().map(([k, v]) => [k, [...v].sort()])),
      riskSummary: risk.summary
    },
    null,
    2
  ) + "\n";

const stale = [];
if (!checkMode) fs.mkdirSync(outDir, { recursive: true });
for (const [name, content] of Object.entries(pages)) {
  const target = path.join(outDir, name);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  if (current === content) continue;
  if (checkMode) stale.push(name);
  else fs.writeFileSync(target, content);
}
if (!checkMode) {
  const known = new Set(Object.keys(pages));
  for (const name of fs.readdirSync(outDir)) if (!known.has(name)) fs.rmSync(path.join(outDir, name));
}

if (checkMode && stale.length) {
  console.error(`Knowledge base is stale: ${stale.map((s) => `docs/kb/generated/${s}`).join(", ")}`);
  console.error("Run `npm run kb:generate` and commit the result.");
  process.exit(1);
}
console.log(
  `kb: ${routes.length} routes, ${schema.tables.length} tables, ${envReads.size} env vars` + (checkMode ? " — up to date" : " — written to docs/kb/generated")
);
