export const SYNTHETIC_SEED = "crewcue-pacing-eval-synthetic-v1";
export const SYNTHETIC_GENERATOR_PATH = "services/api/src/lib/pacingEstimate/evaluation/synthetic.ts";
const SYNTHETIC_NOTE =
  "SYNTHETIC. Generated by an independent truth model (Minetti 2002 cost, Tobler hiking, per-athlete Riegel exponent, descent damage, noise). Exercises the harness and regression gate; not real-world evidence.";

const ATHLETE_COUNT = 10;
const ROUTE_SPACING_METERS = 200;
const METERS_PER_DEGREE_LATITUDE = 111_000;
/** Riegel anchor distance for an athlete's fresh flat speed. */
const REFERENCE_DISTANCE_METERS = 20_000;

// ---------------------------------------------------------------------------------------------
// Seeded randomness
// ---------------------------------------------------------------------------------------------

export type Rng = {
  next(): number;
  uniform(min: number, max: number): number;
  normal(mean: number, sd: number): number;
};

/** mulberry32 seeded from SHA-256 of a label, so every stream is independent and reproducible. */
export function createRng(label: string): Rng {
  let state = createHash("sha256").update(label).digest().readUInt32BE(0);
  const next = (): number => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return {
    next,
    uniform: (min, max) => min + (max - min) * next(),
    normal: (mean, sd) => {
      const u1 = Math.max(next(), 1e-12);
      const u2 = next();
      return mean + sd * Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
    }
  };
}

