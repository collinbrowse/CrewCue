export type ProfileSpec = {
  lengthMeters: number;
  gainMeters: number;
  baseElevationMeters: number;
};

/** Block-wise random grades scaled to the target gain, sampled every ROUTE_SPACING_METERS. */
export function generateProfile(spec: ProfileSpec, rng: Rng): { distances: number[]; elevations: number[] } {
  const steps = Math.round(spec.lengthMeters / ROUTE_SPACING_METERS);
  const stepMeters = spec.lengthMeters / steps;
  const meanClimbGrade = spec.gainMeters / (spec.lengthMeters / 2);
  const band = Math.max(150, Math.min(spec.gainMeters / 3, 1500));
  const grades: number[] = [];
  let elevation = 0;
  while (grades.length < steps) {
    const blockSteps = Math.max(1, Math.round((rng.uniform(500, 3000) / stepMeters)));
    const goUp = elevation < band * rng.uniform(0.2, 0.8);
    const magnitude = Math.min(0.3, meanClimbGrade * rng.uniform(0.3, 1.7));
    for (let i = 0; i < blockSteps && grades.length < steps; i += 1) {
      const grade = (goUp ? 1 : -1) * magnitude;
      grades.push(grade);
      elevation += grade * stepMeters;
    }
  }
  const rawGain = grades.reduce((sum, grade) => sum + Math.max(0, grade) * stepMeters, 0);
  const scale = rawGain > 0 ? spec.gainMeters / rawGain : 0;

  const distances = [0];
  const raw = [0];
  for (let index = 0; index < steps; index += 1) {
    distances.push((index + 1) * stepMeters);
    raw.push(raw[index]! + grades[index]! * scale * stepMeters);
  }
  const minimum = Math.min(...raw);
  const elevations = raw.map((value) => Math.round((value - minimum + spec.baseElevationMeters) * 10) / 10);
  return { distances, elevations };
}

