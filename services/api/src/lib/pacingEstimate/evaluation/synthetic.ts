/**
 * SYNTHETIC evaluation corpus generator. Output is labelled `provenance.kind: "synthetic"` and is
 * never evidence of real-world accuracy.
 *
 * Why it exists: no permissively licensed corpus of timed ultra efforts paired with the runner's
 * pre-race history was found (see docs/sdlc/pacing-evaluation.md). Synthetic efforts keep the
 * harness, its baselines, and the CI regression gate exercised until real efforts are imported.
 *
 * To avoid grading the production model against itself, the "truth" here is a deliberately
 * DIFFERENT model built from published forms the production model does not use:
 * - grade cost: Minetti et al. (2002) energy-cost polynomial (production uses its own quadratics);
 * - power-hiking above a per-athlete grade, at Tobler-hiking-function speed;
 * - downhill gain capped per athlete and eroded by cumulative descent (quad damage), with a
 *   technical penalty on steep descents;
 * - per-athlete Riegel exponent 1.06–1.18 (production uses a fixed endurance exponent);
 * - fade over distance, altitude sensitivity from 1200 m, day-form and per-km noise;
 * - history summaries carry GPS distance error, elevation-gain error, and stop time in elapsed.
 *
 * Deterministic for a seed: the committed corpus must equal a fresh generation (tested).
 */
