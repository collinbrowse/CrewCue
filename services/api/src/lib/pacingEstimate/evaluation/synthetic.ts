const HISTORY_DISTANCE_BANDS: ReadonlyArray<[number, number]> = [
  [8000, 15_000], [8000, 15_000], [8000, 15_000], [8000, 15_000],
  [16_000, 30_000], [16_000, 30_000], [16_000, 30_000], [16_000, 30_000],
  [30_000, 50_000], [30_000, 50_000]
];

/** Pre-race training summaries as Strava/GPX would report them (noisy distance/gain, stops). */
export function generateHistory(athlete: SyntheticAthlete, raceStartAt: string, seed = SYNTHETIC_SEED): ActivityHistoryRef[] {
  const rng = createRng(`${seed}:history:${athlete.key}:${raceStartAt}`);
  const raceMs = Date.parse(raceStartAt);
  return HISTORY_DISTANCE_BANDS.map(([min, max], index) => {
    const distance = rng.uniform(min, max);
    const gainPerKm = rng.uniform(5, 45);
    const profile = generateProfile(
      { lengthMeters: distance, gainMeters: (distance / 1000) * gainPerKm, baseElevationMeters: rng.uniform(100, 1200) },
      rng
    );
    const moving = simulateTruthElapsed(profile.distances, profile.elevations, athlete, {
      effortDistanceMeters: distance,
      form: Math.exp(rng.normal(0, 0.05)),
      noiseSd: 0.05,
      rng
    });
    const trueGain = profile.elevations.reduce(
      (sum, elevation, i) => (i === 0 ? sum : sum + Math.max(0, elevation - profile.elevations[i - 1]!)),
      0
    );
    const daysBefore = 7 + Math.floor(rng.uniform(0, 110));
    const recordedAt = new Date(raceMs - daysBefore * 86_400_000 - 5 * 3600_000).toISOString();
    const id = `${athlete.key}-run-${String(index + 1).padStart(2, "0")}`;
    return {
      id,
      source: "gpx_upload" as const,
      externalId: `synthetic:${id}:${raceStartAt.slice(0, 10)}`,
      recordedAt,
      ingestedAt: new Date(raceMs - 3 * 86_400_000).toISOString(),
      distanceMeters: Math.round(distance * rng.uniform(0.985, 1.025) * 10) / 10,
      elapsedSeconds: Math.round(moving[moving.length - 1]! * (1 + rng.uniform(0, 0.06))),
      elevationGainMeters: Math.round(trueGain * rng.uniform(0.85, 1.2))
    };
  });
}

export function generateEffort(input: {
  athlete: SyntheticAthlete;
  courseKey: string;
  coursePath: string;
  courseGpxXml: string;
  raceStartAt: string;
  seed?: string;
}): EvaluationEffort {
  const seed = input.seed ?? SYNTHETIC_SEED;
  const geometry = courseGeometryFromGpx(input.courseGpxXml);
  const rng = createRng(`${seed}:race:${input.athlete.key}:${input.courseKey}`);
  const elapsed = simulateTruthElapsed(geometry.distances, geometry.elevations, input.athlete, {
    effortDistanceMeters: geometry.lengthMeters,
    form: Math.exp(rng.normal(0, 0.04)),
    noiseSd: 0.05,
    rng
  });
  const actualSplits = geometry.checkpoints
    .filter((checkpoint) => checkpoint.distanceMetersFromStart > 0 && checkpoint.id !== "finish")
    .filter((checkpoint) => checkpoint.distanceMetersFromStart < geometry.lengthMeters - 1)
    .map((checkpoint) => ({
      checkpointId: checkpoint.id,
      actualElapsedSeconds: Math.round(interpolate(geometry.distances, elapsed, checkpoint.distanceMetersFromStart))
    }))
    .concat([{ checkpointId: "finish", actualElapsedSeconds: Math.round(elapsed[elapsed.length - 1]!) }]);
  return {
    schemaVersion: EVALUATION_EFFORT_SCHEMA_VERSION,
    id: `${input.courseKey}-${input.athlete.key.replace("syn-athlete-", "a")}`,
    group: input.athlete.key,
    provenance: { kind: "synthetic", generator: SYNTHETIC_GENERATOR_PATH, seed, note: SYNTHETIC_NOTE },
    course: input.coursePath,
    raceStartAt: input.raceStartAt,
    history: generateHistory(input.athlete, input.raceStartAt, seed),
    actualSplits,
    tags: ["synthetic", input.courseKey]
  };
}

/**
 * Every synthetic corpus file, keyed by path relative to the corpus root.
 * `readFixture` reads a path relative to the corpus root (for the reused hand-made course).
 */
export function generateSyntheticCorpus(readFixture: (relativePath: string) => string, seed = SYNTHETIC_SEED): Map<string, string> {
  const files = new Map<string, string>();
  const athletes = generateAthletes(seed);
  const courses: Array<{ key: string; path: string; gpx: string; raceStartAt: string }> = [
    { key: FIXTURE_50K_COURSE.key, path: FIXTURE_50K_COURSE.path, gpx: readFixture(FIXTURE_50K_COURSE.path), raceStartAt: FIXTURE_50K_COURSE.raceStartAt }
  ];
  for (const spec of SYNTHETIC_COURSES) {
    const path = `courses/${spec.key}.gpx`;
    const gpx = buildCourseGpx(spec, createRng(`${seed}:course:${spec.key}`));
    files.set(path, gpx);
    courses.push({ key: spec.key, path, gpx, raceStartAt: spec.raceStartAt });
  }
  for (const course of courses) {
    for (const athlete of athletes) {
      const effort = generateEffort({
        athlete,
        courseKey: course.key,
        coursePath: course.path,
        courseGpxXml: course.gpx,
        raceStartAt: course.raceStartAt,
        seed
      });
      files.set(`efforts/${effort.id}.json`, `${JSON.stringify(effort, null, 2)}\n`);
    }
  }
  return files;
}

/** Convenience for scripts/tests: read a corpus-relative path from disk. */
export function corpusFileReader(corpusDir: string): (relativePath: string) => string {
  return (relativePath) => readFileSync(`${corpusDir}/${relativePath}`, "utf8");
}
