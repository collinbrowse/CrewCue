function formatCoordinate(value: number): string {
  return value.toFixed(6);
}

/** Straight north-running course with aid waypoints on route vertices. */
export function buildCourseGpx(spec: SyntheticCourseSpec, rng: Rng): string {
  const { distances, elevations } = generateProfile(spec, rng);
  const startLatitude = 38.5;
  const latitudeAt = (meters: number): number => startLatitude + meters / METERS_PER_DEGREE_LATITUDE;
  const aidIndexes: number[] = [];
  let next = rng.uniform(8000, 14_000);
  for (let index = 1; index < distances.length; index += 1) {
    if (distances[index]! >= next && distances[index]! < spec.lengthMeters - 1500) {
      aidIndexes.push(index);
      next = distances[index]! + rng.uniform(8000, 14_000);
    }
  }
  const waypoint = (name: string, index: number): string =>
    `  <wpt lat="${formatCoordinate(latitudeAt(distances[index]!))}" lon="${formatCoordinate(spec.longitude)}">\n` +
    `    <name>${name}</name>\n    <ele>${elevations[index]!.toFixed(1)}</ele>\n  </wpt>\n`;
  const lines = [
    `<?xml version="1.0" encoding="UTF-8"?>\n`,
    `<gpx version="1.1" creator="crewcue-pacing-eval-synthetic" xmlns="http://www.topografix.com/GPX/1/1">\n`,
    `  <metadata><desc>SYNTHETIC course generated by ${SYNTHETIC_GENERATOR_PATH} (${SYNTHETIC_SEED}). Not a real route.</desc></metadata>\n`,
    waypoint("Start", 0),
    ...aidIndexes.map((index, order) => waypoint(`Aid ${order + 1}`, index)),
    waypoint("Finish", distances.length - 1),
    `  <trk>\n    <name>${spec.title}</name>\n    <trkseg>\n`,
    ...distances.map(
      (meters, index) =>
        `      <trkpt lat="${formatCoordinate(latitudeAt(meters))}" lon="${formatCoordinate(spec.longitude)}"><ele>${elevations[index]!.toFixed(1)}</ele></trkpt>\n`
    ),
    `    </trkseg>\n  </trk>\n</gpx>\n`
  ];
  return lines.join("");
}

type CourseGeometry = {
  distances: number[];
  elevations: number[];
  checkpoints: Array<{ id: string; distanceMetersFromStart: number }>;
  lengthMeters: number;
};

/** Read a course the same way the app does (parse → checkpoints → projected distances). */
export function courseGeometryFromGpx(gpxXml: string): CourseGeometry {
  const parsed = parseGpxTrack(gpxXml);
  const route: CourseMetricPoint[] = parsed.points.map((point) => ({
    latitude: point.latitude,
    longitude: point.longitude,
    elevationMeters: point.elevationMeters
  }));
  const distances = geodesicCumulativeAtVertices(route);
  const elevations = parsed.points.map((point) => point.elevationMeters ?? 0);
  const { course } = buildRaceCourseFromGpx(parsed);
  const checkpoints = checkpointsWithProjectedDistances(course.checkpoints, route).map((checkpoint) => ({
    id: checkpoint.id,
    distanceMetersFromStart: checkpoint.distanceMetersFromStart ?? 0
  }));
  return { distances, elevations, checkpoints, lengthMeters: distances[distances.length - 1] ?? 0 };
}

function interpolate(distances: number[], values: number[], at: number): number {
  if (at <= 0) {
    return values[0]!;
  }
  for (let index = 1; index < distances.length; index += 1) {
    if (at <= distances[index]!) {
      const span = distances[index]! - distances[index - 1]!;
      const t = span > 0 ? (at - distances[index - 1]!) / span : 0;
      return values[index - 1]! + t * (values[index]! - values[index - 1]!);
    }
  }
  return values[values.length - 1]!;
}

