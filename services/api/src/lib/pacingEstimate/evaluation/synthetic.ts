export type SyntheticAthlete = {
  key: string;
  /** Fresh flat speed over REFERENCE_DISTANCE_METERS (m/s). */
  referenceSpeedMps: number;
  /** Riegel time exponent: T ∝ D^exponent. */
  riegelExponent: number;
  /** Grade (rise/run) above which the athlete power-hikes. */
  hikeGrade: number;
  /** Multiplier on Tobler hiking speed. */
  hikeFactor: number;
  /** Max fractional speed gain on downhills when fresh. */
  downhillGain: number;
  /** Cumulative descent (m) that halves the downhill gain. */
  descentToleranceMeters: number;
  altitudeSensitivity: number;
  /** Pace fade amplitude over a 50 km effort (scaled with distance). */
  fade: number;
};

/** Minetti et al. (2002) cost of running, J/kg/m, relative to flat (3.6 J/kg/m). */
export function minettiRelativeCostTruth(grade: number): number {
  const i = Math.max(-0.45, Math.min(0.45, grade));
  const cost = 155.4 * i ** 5 - 30.4 * i ** 4 - 43.3 * i ** 3 + 46.3 * i ** 2 + 19.5 * i + 3.6;
  return cost / 3.6;
}

/** Tobler's hiking function (m/s). */
export function toblerSpeedMps(grade: number): number {
  return (6 * Math.exp(-3.5 * Math.abs(grade + 0.05))) / 3.6;
}

export type TruthOptions = {
  /** Total distance of the effort (Riegel + fade scale). */
  effortDistanceMeters: number;
  /** Day form multiplier on speed (1 = typical). */
  form: number;
  /** Per-km speed noise SD (lognormal); 0 for a noiseless run. */
  noiseSd: number;
  rng: Rng;
};

/** Moving elapsed seconds at each profile vertex. */
export function simulateTruthElapsed(
  distances: number[],
  elevations: number[],
  athlete: SyntheticAthlete,
  options: TruthOptions
): number[] {
  const { effortDistanceMeters: total } = options;
  const enduranceSpeed =
    athlete.referenceSpeedMps * Math.pow(REFERENCE_DISTANCE_METERS / total, athlete.riegelExponent - 1) * options.form;
  const fade = athlete.fade * Math.min(2, Math.max(0.3, total / 50_000));
  const kmNoise: number[] = [];
  const noiseFor = (meters: number): number => {
    const km = Math.floor(meters / 1000);
    while (kmNoise.length <= km) {
      kmNoise.push(options.noiseSd > 0 ? Math.exp(options.rng.normal(0, options.noiseSd)) : 1);
    }
    return kmNoise[km]!;
  };

  const elapsed = [0];
  let descent = 0;
  for (let index = 1; index < distances.length; index += 1) {
    const dx = distances[index]! - distances[index - 1]!;
    if (!(dx > 0)) {
      elapsed.push(elapsed[index - 1]!);
      continue;
    }
    const dz = elevations[index]! - elevations[index - 1]!;
    const grade = dz / dx;
    const altitude = (elevations[index]! + elevations[index - 1]!) / 2;
    const progress = (distances[index - 1]! + dx / 2) / total;

    let speed: number;
    if (grade >= 0) {
      speed = enduranceSpeed / minettiRelativeCostTruth(grade);
      if (grade >= athlete.hikeGrade) {
        speed = Math.min(speed, toblerSpeedMps(grade) * athlete.hikeFactor);
      }
    } else {
      const benefit = 1 / minettiRelativeCostTruth(grade);
      const damage = 1 / (1 + descent / athlete.descentToleranceMeters);
      const technical = grade < -0.12 ? 3 * (-grade - 0.12) : 0;
      const cap = 1 + athlete.downhillGain * damage - technical;
      speed = enduranceSpeed * Math.max(0.5, Math.min(benefit, cap));
      descent += -dz;
    }
    if (altitude > 1200) {
      speed *= Math.max(0.75, 1 - 0.008 * athlete.altitudeSensitivity * ((altitude - 1200) / 300));
    }
    const paceMultiplier = 1 + fade * (progress - 0.5);
    speed = (speed / paceMultiplier) * noiseFor(distances[index - 1]!);
    elapsed.push(elapsed[index - 1]! + dx / speed);
  }
  return elapsed;
}

export function generateAthletes(seed = SYNTHETIC_SEED): SyntheticAthlete[] {
  return Array.from({ length: ATHLETE_COUNT }, (_, index) => {
    const key = `syn-athlete-${String(index + 1).padStart(2, "0")}`;
    const rng = createRng(`${seed}:athlete:${key}`);
    const referenceSpeedMps = rng.uniform(2.5, 3.7);
    return {
      key,
      referenceSpeedMps,
      riegelExponent: rng.uniform(1.06, 1.18),
      hikeGrade: rng.uniform(0.08, 0.18),
      hikeFactor: rng.uniform(1.0, 1.5) * (referenceSpeedMps / 3),
      downhillGain: rng.uniform(0.15, 0.45),
      descentToleranceMeters: rng.uniform(1500, 6000),
      altitudeSensitivity: rng.uniform(0.5, 1.5),
      fade: rng.uniform(0.05, 0.25)
    };
  });
}

