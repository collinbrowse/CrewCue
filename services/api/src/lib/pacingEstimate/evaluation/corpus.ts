/**
 * Pacing evaluation corpus: completed efforts (course + pre-race history + actual moving splits).
 *
 * One JSON file per effort under `<corpus>/efforts/`, course GPX under `<corpus>/courses/`.
 * See docs/sdlc/pacing-evaluation.md for how to add efforts and what provenance is allowed.
 *
 * Tune/holdout assignment is derived from a hash of the effort's `group` (one athlete), never
 * stored in the file. Contributors cannot choose which side an effort lands on, and the same
 * athlete never appears on both sides, so constants tuned on `tune` are judged on unseen athletes.
 */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { parseActivityHistoryRef, parseIso8601Utc, type ActivityHistoryRef } from "@crewcue/contracts";
import type { BacktestActualSplit } from "../backtest.js";

export const EVALUATION_EFFORT_SCHEMA_VERSION = 1;

/** Share of athlete groups held out from tuning. */
export const HOLDOUT_FRACTION = 0.3;
const SPLIT_SALT = "crewcue-pacing-eval-split-v1";

export type EvaluationSplit = "tune" | "holdout";

export type EffortProvenance =
  /** Generated by the committed synthetic generator. Never evidence of real-world accuracy. */
  | { kind: "synthetic"; generator: string; seed: string; note: string }
  /** A completed effort by the contributor (or with their explicit consent). */
  | { kind: "own-effort"; contributor: string; consent: string; note?: string }
  /** Public data under a license that allows redistribution (public domain, CC0, CC BY, ODbL...). */
  | { kind: "public"; source: string; license: string; note?: string };

export type EvaluationEffort = {
  schemaVersion: typeof EVALUATION_EFFORT_SCHEMA_VERSION;
  /** Stable unique id, also the file name stem. */
  id: string;
  /** Athlete pseudonym. Efforts by one athlete share a group, so they share a split. */
  group: string;
  provenance: EffortProvenance;
  /** Course GPX path relative to the corpus root (waypoints become checkpoints). */
  course: string;
  raceStartAt: string;
  /** Activity summaries the athlete had BEFORE the race (what the app would have seen). */
  history: ActivityHistoryRef[];
  /** MOVING elapsed from the start at each checkpoint (aid dwell excluded). Must include `finish`. */
  actualSplits: BacktestActualSplit[];
  tags?: string[];
};

export type LoadedEffort = EvaluationEffort & {
  split: EvaluationSplit;
  courseGpxXml: string;
};

export class EvaluationCorpusError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "EvaluationCorpusError";
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function requireString(value: unknown, field: string): string {
  if (typeof value !== "string" || value.trim().length === 0) {
    throw new EvaluationCorpusError(`${field} must be a non-empty string`);
  }
  return value;
}

function optionalString(value: unknown, field: string): string | undefined {
  return value === undefined ? undefined : requireString(value, field);
}

function parseProvenance(value: unknown, field: string): EffortProvenance {
  if (!isRecord(value)) {
    throw new EvaluationCorpusError(`${field} must be an object`);
  }
  switch (value.kind) {
    case "synthetic":
      return {
        kind: "synthetic",
        generator: requireString(value.generator, `${field}.generator`),
        seed: requireString(value.seed, `${field}.seed`),
        note: requireString(value.note, `${field}.note`)
      };
    case "own-effort": {
      const note = optionalString(value.note, `${field}.note`);
      return {
        kind: "own-effort",
        contributor: requireString(value.contributor, `${field}.contributor`),
        consent: requireString(value.consent, `${field}.consent`),
        ...(note !== undefined ? { note } : {})
      };
    }
    case "public": {
      const note = optionalString(value.note, `${field}.note`);
      return {
        kind: "public",
        source: requireString(value.source, `${field}.source`),
        license: requireString(value.license, `${field}.license`),
        ...(note !== undefined ? { note } : {})
      };
    }
    default:
      throw new EvaluationCorpusError(`${field}.kind must be synthetic, own-effort, or public`);
  }
}

function parseActualSplits(value: unknown, field: string): BacktestActualSplit[] {
  if (!Array.isArray(value) || value.length === 0) {
    throw new EvaluationCorpusError(`${field} must be a non-empty array`);
  }
  const seen = new Set<string>();
  const splits = value.map((row, index) => {
    if (!isRecord(row)) {
      throw new EvaluationCorpusError(`${field}[${index}] must be an object`);
    }
    const checkpointId = requireString(row.checkpointId, `${field}[${index}].checkpointId`);
    const seconds = row.actualElapsedSeconds;
    if (typeof seconds !== "number" || !Number.isFinite(seconds) || seconds <= 0) {
      throw new EvaluationCorpusError(`${field}[${index}].actualElapsedSeconds must be a positive number`);
    }
    if (seen.has(checkpointId)) {
      throw new EvaluationCorpusError(`${field} repeats checkpointId ${checkpointId}`);
    }
    seen.add(checkpointId);
    return { checkpointId, actualElapsedSeconds: seconds };
  });
  if (!seen.has("finish")) {
    throw new EvaluationCorpusError(`${field} must include a finish split`);
  }
  return splits;
}

export function parseEvaluationEffort(value: unknown, source = "effort"): EvaluationEffort {
  if (!isRecord(value)) {
    throw new EvaluationCorpusError(`${source} must be a JSON object`);
  }
  if (value.schemaVersion !== EVALUATION_EFFORT_SCHEMA_VERSION) {
    throw new EvaluationCorpusError(
      `${source}.schemaVersion must be ${EVALUATION_EFFORT_SCHEMA_VERSION}`
    );
  }
  const id = requireString(value.id, `${source}.id`);
  if (!/^[a-z0-9][a-z0-9-]*$/.test(id)) {
    throw new EvaluationCorpusError(`${source}.id must be lowercase kebab-case`);
  }
  let raceStartAt: string;
  try {
    raceStartAt = parseIso8601Utc(value.raceStartAt, `${source}.raceStartAt`);
  } catch (error) {
    throw new EvaluationCorpusError((error as Error).message);
  }
  if (!Array.isArray(value.history)) {
    throw new EvaluationCorpusError(`${source}.history must be an array (empty = cold start)`);
  }
  let history: ActivityHistoryRef[];
  try {
    history = value.history.map((row, index) => parseActivityHistoryRef(row, `${source}.history[${index}]`));
  } catch (error) {
    throw new EvaluationCorpusError((error as Error).message);
  }
  const raceStartMs = Date.parse(raceStartAt);
  for (const row of history) {
    if (Date.parse(row.recordedAt) >= raceStartMs) {
      throw new EvaluationCorpusError(
        `${source}.history ${row.id} was recorded at or after the race start; only pre-race history may be used`
      );
    }
  }
  let tags: string[] | undefined;
  if (value.tags !== undefined) {
    if (!Array.isArray(value.tags)) {
      throw new EvaluationCorpusError(`${source}.tags must be an array of strings`);
    }
    tags = value.tags.map((tag, index) => requireString(tag, `${source}.tags[${index}]`));
  }
  return {
    schemaVersion: EVALUATION_EFFORT_SCHEMA_VERSION,
    id,
    group: requireString(value.group, `${source}.group`),
    provenance: parseProvenance(value.provenance, `${source}.provenance`),
    course: requireString(value.course, `${source}.course`),
    raceStartAt,
    history,
    actualSplits: parseActualSplits(value.actualSplits, `${source}.actualSplits`),
    ...(tags !== undefined ? { tags } : {})
  };
}

/** Deterministic split from the athlete group (salted SHA-256, first 32 bits as a unit fraction). */
export function assignEvaluationSplit(group: string): EvaluationSplit {
  const digest = createHash("sha256").update(`${SPLIT_SALT}:${group}`).digest();
  const fraction = digest.readUInt32BE(0) / 0x1_0000_0000;
  return fraction < HOLDOUT_FRACTION ? "holdout" : "tune";
}

export function loadEvaluationCorpus(corpusDir: string): LoadedEffort[] {
  const effortsDir = resolve(corpusDir, "efforts");
  if (!existsSync(effortsDir)) {
    throw new EvaluationCorpusError(`No efforts directory at ${effortsDir}`);
  }
  const courseCache = new Map<string, string>();
  const efforts = readdirSync(effortsDir)
    .filter((name) => name.endsWith(".json"))
    .sort()
    .map((fileName) => {
      const raw: unknown = JSON.parse(readFileSync(resolve(effortsDir, fileName), "utf8"));
      const effort = parseEvaluationEffort(raw, fileName);
      if (`${effort.id}.json` !== fileName) {
        throw new EvaluationCorpusError(`${fileName}: id ${effort.id} must match the file name`);
      }
      let courseGpxXml = courseCache.get(effort.course);
      if (courseGpxXml === undefined) {
        const coursePath = resolve(corpusDir, effort.course);
        if (!existsSync(coursePath)) {
          throw new EvaluationCorpusError(`${fileName}: course ${effort.course} not found`);
        }
        courseGpxXml = readFileSync(coursePath, "utf8");
        courseCache.set(effort.course, courseGpxXml);
      }
      return { ...effort, split: assignEvaluationSplit(effort.group), courseGpxXml };
    });
  if (efforts.length === 0) {
    throw new EvaluationCorpusError(`No effort files in ${effortsDir}`);
  }
  return efforts;
}

/**
 * Fingerprint of corpus content (efforts + course files) so a stored metrics baseline can tell a
 * model regression apart from a corpus change.
 */
export function corpusFingerprint(efforts: LoadedEffort[]): string {
  const hash = createHash("sha256");
  for (const effort of [...efforts].sort((a, b) => a.id.localeCompare(b.id))) {
    const { courseGpxXml, split: _split, ...data } = effort;
    hash.update(JSON.stringify(data));
    hash.update(createHash("sha256").update(courseGpxXml).digest("hex"));
  }
  return hash.digest("hex").slice(0, 16);
}
